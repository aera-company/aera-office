#!/usr/bin/env python3
"""Writes api/_site-context.js: what NAYRA may say on the public site (C87). Run it after confirming new AERA facts."""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from office.store import Store
from office import nayra

store = Store(ROOT / 'runtime' / 'office.sqlite3')
try:
    context = nayra.site_context(store, nayra.resolve_client(store, 'AERA'))
finally:
    store.close()
body = json.dumps(context, ensure_ascii=False, indent=1)
(ROOT / 'api' / '_site-context.js').write_text(
    '// Generated by scripts/nayra_site_context.py. AERA confirmed facts only; this repository is public.\nexport default ' + body + ';\n', encoding='utf-8')
print(f'{context["facts"]} fatos no contexto do site.')
